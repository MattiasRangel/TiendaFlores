    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        if (jComboBox1.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Selecciona un producto");
            return;
        }

        String producto = jComboBox1.getSelectedItem().toString().trim();
        String unidades = jTextField1.getText().trim();

        if (unidades.isEmpty() || unidades.equals("0")) {
            JOptionPane.showMessageDialog(this, "Ingresa cantidad válida");
            return;
        }

        
        String msg = control.llenar_venta(producto, unidades);
        JOptionPane.showMessageDialog(this, msg);

        jTextField1.setText("");  // Limpia

        
    }//GEN-LAST:event_jButton1ActionPerformed

