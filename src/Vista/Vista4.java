    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String nombre = jTextField1.getText();
        String precio = jTextField2.getText();
        String color = jTextField4.getText();
        String cantidad = jTextField3.getText();
        String origen = jTextField5.getText();
        
        Controlador control = new Controlador();
        if (nombre.equalsIgnoreCase("") || precio.equalsIgnoreCase("")) {
            JOptionPane.showMessageDialog(null, "No se pueden dejar los campos vacios");
        } 
        
        
            control.llenar_inv(nombre, precio, cantidad, color, origen);            
            JOptionPane.showMessageDialog(null, "Producto registrado exitosamente");
            Vista3 meth = new Vista3();
            meth.setVisible(true);
            setVisible(false);
        
    }//GEN-LAST:event_jButton1ActionPerformed

