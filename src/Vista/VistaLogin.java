    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String contraseña = jPasswordField1.getText();
        String usuario = jTextField3.getText();
        

        Controlador control = new Controlador();
        
        
        
        
        if (usuario.equalsIgnoreCase("") || contraseña.equalsIgnoreCase("")) {
        JOptionPane.showMessageDialog(null, "No se pueden dejar los campos vacíos");
        return; 
    } 
    
    
    Modelo.ResultadoLogin resultado = control.Validar_datos(usuario, contraseña);
    
    

    if (resultado.isExito()) { 
        
 
        if (!jRadioButton1.isSelected() && !jRadioButton2.isSelected()) {
            JOptionPane.showMessageDialog(null, "Debe seleccionar un rol para ingresar");
            return;
        }
        
        int rolEncontrado = resultado.getRol();
        
        if (jRadioButton1.isSelected()) { 
            if (rolEncontrado == 1){
                VistaMenuFlorista meth = new VistaMenuFlorista();
                meth.setVisible(true);
                setVisible(false);
            } else {
                JOptionPane.showMessageDialog(null, "El rol (Florista) no concuerda con el usuario.");
            }
        } else if (jRadioButton2.isSelected()) { 
            if (rolEncontrado == 2){
                
                VistaMenuCajero meth = new VistaMenuCajero();
                meth.setVisible(true);
                setVisible(false);
            } else {
                JOptionPane.showMessageDialog(null, "El rol (Cajero) no concuerda con el usuario.");
            }
        }
        
    } else {
     
        JOptionPane.showMessageDialog(null, "Usuario o contraseña incorrectos.");
    }
        
        
        


    }//GEN-LAST:event_jButton1ActionPerformed

